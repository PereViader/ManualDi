using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using NUnit.Framework;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using System.Text;
using System.Threading.Tasks;
using ManualDi.Sync.Generators;
using VerifyNUnit;

namespace ManualDi.Sync.Tests;

[TestFixture]
public class TestsSourceGenerator
{
    [Test]
    public Task Generated()
    {
        var code = File.ReadAllText("TestSourceGenerator.Source.cs");
        var generated = GeneratorTestHelper.Generate(code);
        Assert.That(generated.diagnostics, Is.Empty);
        return Verifier.Verify(generated.code);
    }

    [Test]
    public void Generated_WithXmlDocsAndObsoleteTypes_NoDiagnostics()
    {
        const string code = """
            #pragma warning disable CS0612, CS1591
            using System;
            using ManualDi.Sync;

            namespace TestNamespace
            {
                [Obsolete]
                public class ObsoleteDep
                {
                }

                [Obsolete]
                [ManualDi]
                public class ObsoleteBase
                {
                }

                [ManualDi]
                public class Consumer : ObsoleteBase
                {
                    public Consumer(ObsoleteDep dep)
                    {
                    }

                    public void Inject(ObsoleteDep dep)
                    {
                    }
                }
            }
            """;

        var references = AppDomain.CurrentDomain
            .GetAssemblies()
            .Where(a => !a.IsDynamic && !string.IsNullOrEmpty(a.Location) && !a.Location.Contains("ManualDi.Sync.Tests.dll"))
            .Select(a => MetadataReference.CreateFromFile(a.Location))
            .ToList();

        references.Add(MetadataReference.CreateFromFile(typeof(IDiContainer).Assembly.Location));

        var parseOptions = CSharpParseOptions.Default.WithDocumentationMode(DocumentationMode.Diagnose);
        var compilation = CSharpCompilation.Create(
            "AssemblyName",
            [CSharpSyntaxTree.ParseText(SourceText.From(code, Encoding.UTF8), parseOptions)],
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, generalDiagnosticOption: ReportDiagnostic.Error)
                .WithNullableContextOptions(NullableContextOptions.Enable));

        var driver = CSharpGeneratorDriver.Create(
            [new ManualDiSourceGenerator().AsSourceGenerator()],
            parseOptions: parseOptions);
        driver.RunGeneratorsAndUpdateCompilation(compilation, out var outputCompilation, out var generatorDiagnostics);

        Assert.That(generatorDiagnostics, Is.Empty);
        Assert.That(outputCompilation.GetDiagnostics(), Is.Empty);

        var generatedTrees = outputCompilation.SyntaxTrees.Skip(1).ToList();
        Assert.That(generatedTrees, Is.Not.Empty);
        foreach (var tree in generatedTrees)
        {
            var text = tree.ToString();
            Assert.That(text, Does.StartWith("// <auto-generated/>"));
            Assert.That(text, Does.Contain("#pragma warning disable"));
        }
    }
}